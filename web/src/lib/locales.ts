const langCell = signal<Lang>(DEFAULT_LANG)
let initialized = false

export const currentLang = () => langCell.use()

export function storedLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY)
    if (v === "en" || v === "ar") return v
  } catch { /* private mode */ }
  return DEFAULT_LANG
}

export function setLang(next: Lang): void {
  if (next === langCell.use() && initialized) return
  langCell.set(next)
  try { localStorage.setItem(LANG_KEY, next) } catch { /* private mode */ }
  const root = document.documentElement
  root.dir = RTL_LANGS[next] ? "rtl" : "ltr"
  root.lang = next
  initialized = true
}

export function initLang(): Lang {
  const lang = storedLang()
  setLang(lang)
  return lang
}

export function isRtl(): boolean {
  return RTL_LANGS[langCell.use()] ?? false
}

export function t(path: string, params?: Record<string, string | number>): string {
  const lang = langCell.use()
  let value = get(translations[lang], path)
  if (value === undefined) value = get(translations.en, path)
  if (typeof value !== "string") value = path
  return interpolate(value, params)
}

export function useLang(): Lang {
  return langCell.use()
}







