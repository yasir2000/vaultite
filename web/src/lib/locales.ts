type Dict = Record<string, unknown>

function get(obj: Dict, path: string): unknown {
  let cur: unknown = obj
  for (const part of path.split(".")) {
    if (!cur || typeof cur !== "object" || !(part in cur)) return undefined
    cur = (cur as Dict)[part]
  }
  return cur
}

